# import math
# math.PI

# AttributeError: module 'math' has no attribute 'PI'

# KeyError

# user['name']

# KeyError: 'county'

# TypeError:

# 4 + '3'

# TypeError; unsupported operand for type(s) for +: 'int' and 'str'

