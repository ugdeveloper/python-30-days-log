## Error types

# Syntax Error

#     print 'hello world'
#                       ^
# SyntaxError: Missing parentheses in call to 'print'. Did you mean print('hello world')?

# Name Error

#     print(age)
#
# NameError: name 'age' is not defined

# index error (indexoutofboundexception)

# >>> import maths
#
# ModuleNotFoundError: No module named 'maths'

